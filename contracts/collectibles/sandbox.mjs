import {Worker} from 'near-workspaces';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const worker=await Worker.init();
try{
 const root=worker.rootAccount;
 const [owner,seller,buyer]=await Promise.all(['owner','seller','buyer'].map(n=>root.createSubAccount(n)));
 const contract=await root.devDeploy(process.env.CONTRACT_WASM || fileURLToPath(new URL('./target/wasm32-unknown-unknown/release/deepfish_collectibles.wasm',import.meta.url)));
 const call=(who,method,args={},deposit='0')=>who.call(contract,method,args,{attachedDeposit:deposit,gas:'100000000000000'});
 const storage='10000000000000000000000';
 await call(owner,'new',{owner_id:owner.accountId,fee_bps:250});
 await call(owner,'register',{},storage);await call(seller,'register',{},storage);
 const token='collectible-sandbox';
 const mint={token_id:token,receiver_id:seller.accountId,title:'Coral demo',description:'Collectible; not catch proof'};
 await call(owner,'nft_mint',mint,'100000000000000000000000');
 await assert.rejects(call(owner,'nft_mint',mint,'100000000000000000000000'),/unique/);
 const price='1000000000000000000000000';
 const block=await worker.provider.block({finality:'final'});
 const expires=(BigInt(block.header.timestamp_nanosec)+86400000000000n).toString();
 await call(seller,'list',{token_id:token,price,expires_at:expires},storage);
 assert.equal((await contract.view('nft_token',{token_id:token})).owner_id,contract.accountId);
 await assert.rejects(call(buyer,'buy',{token_id:token},'1'),/Exact payment/);
 assert.equal((await contract.view('nft_token',{token_id:token})).owner_id,contract.accountId);
 await assert.rejects(call(buyer,'delist',{token_id:token},'1'),/Seller only/);
 await call(buyer,'buy',{token_id:token},price);
 assert.equal((await contract.view('nft_token',{token_id:token})).owner_id,buyer.accountId);
 assert.equal(await contract.view('listing',{token_id:token}),null);
 const available=BigInt(await contract.view('balance_of',{account_id:seller.accountId}));
 assert.equal(available,BigInt(price)*9750n/10000n+BigInt(storage));
 await assert.rejects(call(buyer,'buy',{token_id:token},price),/Not listed/);
 await call(seller,'withdraw',{},'1');
 assert.equal(await contract.view('balance_of',{account_id:seller.accountId}),'0');
 await call(buyer,'nft_transfer',{token_id:token,receiver_id:seller.accountId},'1');
 assert.equal((await contract.view('nft_token',{token_id:token})).owner_id,seller.accountId);
 await call(seller,'list',{token_id:token,price,expires_at:expires},storage);
 await call(seller,'delist',{token_id:token},'1');
 assert.equal((await contract.view('nft_token',{token_id:token})).owner_id,seller.accountId);
 console.log('PASS local sandbox: mint, duplicate rejection, escrow, exact payment rollback, unauthorized delist, settlement, duplicate buy, withdrawal callback, transfer, delist');
}finally{await worker.tearDown();}
